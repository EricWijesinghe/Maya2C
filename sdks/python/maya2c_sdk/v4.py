"""Read, write and describe the v4 transaction payloads (ADR-135).

A payload is ``tag(1) || fields`` as ``crates/node/src/core/*_payload.rs``
writes it: addresses and ids 32 bytes, ``U256`` 32 bytes little-endian,
``u64``/``u32`` little-endian, a name label one length byte then ASCII.

This module only reads and previews payloads. Transactions are still built and
signed by the Rust wallet: a frame or a signature written here would be a
second thing that can disagree with the chain. The words ``describe`` returns
are the node's own (``core::describe``); ``spec/tests/v4-client-vectors.json``,
generated by the node, pins both the bytes and the words, and this module's
tests fail if either drifts.

Fields are a ``dict[str, str]``: integers as decimal strings, bytes as
lowercase hex, labels and symbols as ASCII, the same shape as the vectors.
Standard library only.
"""

from __future__ import annotations

from typing import Final

Fields = dict[str, str]

_U8: Final = (1 << 8) - 1
_U32: Final = (1 << 32) - 1
_U64: Final = (1 << 64) - 1
_U256: Final = (1 << 256) - 1
_SYMBOL_LEN: Final = 8
_MIN_LABEL: Final = 3
_MAX_LABEL: Final = 63

# (tag, field layout) per form. Kinds: "b32" 32 raw bytes, "u256", "u64",
# "u32", "u8", "symbol", "label"; update_name is laid out by hand.
_FORMS: Final[dict[str, tuple[int, tuple[tuple[str, str], ...]]]] = {
    "register_capped_asset": (
        55,
        (("symbol", "symbol"), ("total_supply", "u256"), ("cap", "u256"), ("authority", "b32")),
    ),
    "mint_asset": (56, (("asset", "b32"), ("to", "b32"), ("amount", "u256"))),
    "burn_asset": (57, (("asset", "b32"), ("amount", "u256"))),
    "renounce_mint": (58, (("asset", "b32"),)),
    "create_collection": (59, (("max_items", "u64"), ("metadata_hash", "b32"))),
    "mint_item": (60, (("collection", "b32"), ("metadata_hash", "b32"))),
    "transfer_item": (61, (("collection", "b32"), ("index", "u64"), ("to", "b32"))),
    "burn_item": (62, (("collection", "b32"), ("index", "u64"))),
    "commit_name": (63, (("commitment", "b32"),)),
    "register_name": (
        64,
        (("label", "label"), ("salt", "b32"), ("periods", "u8"), ("target", "b32")),
    ),
    "renew_name": (65, (("label", "label"), ("periods", "u8"))),
    "update_name": (66, (("label", "label"),)),
    "create_schedule": (
        67,
        (
            ("payee", "b32"),
            ("amount", "u256"),
            ("first_due", "u64"),
            ("interval", "u64"),
            ("runs", "u32"),
        ),
    ),
    "cancel_schedule": (68, (("schedule_id", "b32"),)),
}
_BY_TAG: Final = {tag: label for label, (tag, _) in _FORMS.items()}
# update_name ops: name -> (byte, carries an address)
_OPS: Final = {"set_target": (0x01, True), "set_reverse": (0x03, False), "transfer": (0x04, True)}
_OPS_BY_BYTE: Final = {byte: name for name, (byte, _) in _OPS.items()}
_INT_MAX: Final = {"u8": _U8, "u32": _U32, "u64": _U64, "u256": _U256}
_INT_LEN: Final = {"u8": 1, "u32": 4, "u64": 8, "u256": 32}


class PayloadError(ValueError):
    """A payload or a field this module refuses: never a guess."""


def validate_label(label: bytes) -> None:
    """The node's label rule: 3-63 bytes of a-z, 0-9, '-', no edge or double '-'."""
    if not _MIN_LABEL <= len(label) <= _MAX_LABEL:
        raise PayloadError("a label is 3 to 63 bytes")
    if any(not (0x61 <= b <= 0x7A or 0x30 <= b <= 0x39 or b == 0x2D) for b in label):
        raise PayloadError("a label is a-z, 0-9 and '-' only")
    if label[:1] == b"-" or label[-1:] == b"-":
        raise PayloadError("a label does not start or end with '-'")
    if b"--" in label:
        raise PayloadError("a label has no '--'")


def _int(fields: Fields, name: str, kind: str) -> int:
    text = fields[name]
    if not text.isdigit():
        raise PayloadError(f"{name} is not a decimal integer")
    value = int(text)
    if value > _INT_MAX[kind]:
        raise PayloadError(f"{name} does not fit {kind}")
    return value


def _put(out: bytearray, fields: Fields, name: str, kind: str) -> None:
    if name not in fields:
        raise PayloadError(f"missing field {name}")
    if kind == "b32":
        raw = bytes.fromhex(fields[name])
        if len(raw) != 32:
            raise PayloadError(f"{name} is not 32 bytes")
        out += raw
    elif kind == "symbol":
        raw = fields[name].encode("ascii")
        if not raw or len(raw) > _SYMBOL_LEN:
            raise PayloadError("a symbol is 1 to 8 ASCII bytes")
        out += raw.ljust(_SYMBOL_LEN, b"\0")
    elif kind == "label":
        raw = fields[name].encode("ascii")
        validate_label(raw)
        out.append(len(raw))
        out += raw
    else:
        out += _int(fields, name, kind).to_bytes(_INT_LEN[kind], "little")


def encode(label: str, fields: Fields) -> bytes:
    """The payload bytes of form ``label`` with ``fields``."""
    if label not in _FORMS:
        raise PayloadError(f"{label} is not a v4 form")
    tag, layout = _FORMS[label]
    out = bytearray([tag])
    for name, kind in layout:
        _put(out, fields, name, kind)
    if label == "update_name":
        op = fields.get("op", "")
        if op not in _OPS:
            raise PayloadError(f"update op {op!r} is not in this build")
        byte, carries = _OPS[op]
        out.append(byte)
        if carries:
            _put(out, fields, "address", "b32")
    return bytes(out)


class _Reader:
    def __init__(self, data: bytes) -> None:
        self.data, self.at = data, 0

    def take(self, n: int) -> bytes:
        if self.at + n > len(self.data):
            raise PayloadError("payload is truncated")
        chunk = self.data[self.at : self.at + n]
        self.at += n
        return chunk


def _get(reader: _Reader, fields: Fields, name: str, kind: str) -> None:
    if kind == "b32":
        fields[name] = reader.take(32).hex()
    elif kind == "symbol":
        raw = reader.take(_SYMBOL_LEN).rstrip(b"\0")
        fields[name] = raw.decode("ascii", errors="replace")
    elif kind == "label":
        raw = reader.take(reader.take(1)[0])
        validate_label(raw)
        fields[name] = raw.decode("ascii")
    else:
        fields[name] = str(int.from_bytes(reader.take(_INT_LEN[kind]), "little"))


def decode(payload: bytes) -> tuple[str, Fields]:
    """``(label, fields)`` of a v4 payload. Refuses unknown tags and trailing bytes."""
    if not payload:
        raise PayloadError("payload is empty")
    label = _BY_TAG.get(payload[0])
    if label is None:
        raise PayloadError(f"tag {payload[0]} is not a v4 form")
    reader = _Reader(payload[1:])
    fields: Fields = {}
    for name, kind in _FORMS[label][1]:
        _get(reader, fields, name, kind)
    if label == "update_name":
        op = _OPS_BY_BYTE.get(reader.take(1)[0])
        if op is None:
            raise PayloadError("name update op is not in this build")
        fields["op"] = op
        if _OPS[op][1]:
            _get(reader, fields, "address", "b32")
    if reader.at != len(reader.data):
        raise PayloadError("trailing bytes after the payload")
    return label, fields


def group_digits(value: int) -> str:
    """``1234567`` reads ``1,234,567``, as ``core::describe::group_digits``."""
    return f"{value:,}"


def _short(hex_text: str) -> str:
    return f"{hex_text[:4]}…{hex_text[-4:]}"


def describe(label: str, fields: Fields) -> tuple[str, bool, list[tuple[str, str]]]:
    """``(summary, careful, details)``: the words a wallet shows, as the node words them."""
    f = fields
    n = lambda k: group_digits(int(f[k]))  # noqa: E731 - one-line formatter
    if label == "register_capped_asset":
        return (
            f"Register an asset with {n('total_supply')} units now, all credited to you, "
            f"and at most {n('cap')} ever.",
            True,
            [("symbol", f["symbol"]), ("mint authority", f["authority"])],
        )
    if label == "mint_asset":
        return (
            f"Create {n('amount')} new units of an asset for {_short(f['to'])}.",
            True,
            [("asset", f["asset"]), ("pay to", f["to"])],
        )
    if label == "burn_asset":
        return (
            f"Destroy {n('amount')} of your units of an asset. This cannot be undone.",
            True,
            [("asset", f["asset"])],
        )
    if label == "renounce_mint":
        return (
            "Give up minting this asset for good. Its cap falls to the current supply.",
            True,
            [("asset", f["asset"])],
        )
    if label == "create_collection":
        return (
            f"Open a collection of up to {n('max_items')} unique items that only you can mint.",
            True,
            [],
        )
    if label == "mint_item":
        return (
            "Mint the next unique item in a collection you created.",
            False,
            [("collection", f["collection"])],
        )
    if label == "transfer_item":
        return (
            f"Send item {f['index']} to {_short(f['to'])}.",
            True,
            [("collection", f["collection"]), ("pay to", f["to"])],
        )
    if label == "burn_item":
        return (
            f"Destroy item {f['index']}. This cannot be undone.",
            True,
            [("collection", f["collection"])],
        )
    if label == "commit_name":
        return ("Commit to a name. Free; you can reveal it after a short wait.", False, [])
    if label == "register_name":
        return (
            f"Register {f['label']}.maya for {f['periods']} year(s). The fee is burned.",
            True,
            [("name target", f["target"])],
        )
    if label == "renew_name":
        return (
            f"Extend {f['label']}.maya by {f['periods']} year(s). The fee is burned.",
            True,
            [],
        )
    if label == "update_name":
        name, op = f["label"], f["op"]
        if op == "set_target":
            return (
                f"Point {name}.maya at {_short(f['address'])}.",
                True,
                [("name target", f["address"])],
            )
        if op == "set_reverse":
            return (f"Show {name}.maya as the name of your address.", False, [])
        return (f"Give {name}.maya to {_short(f['address'])}.", True, [("new owner", f["address"])])
    if label == "create_schedule":
        return (
            f"Pay {n('amount')} {f['runs']} times to {_short(f['payee'])}, every {f['interval']} "
            f"blocks from block {f['first_due']}. All of it, and the run fees, leave your "
            "balance now.",
            True,
            [("pay to", f["payee"])],
        )
    if label == "cancel_schedule":
        return (
            "Cancel a scheduled payment. What it has not paid yet comes back to you.",
            False,
            [("schedule", f["schedule_id"])],
        )
    raise PayloadError(f"{label} is not a v4 form")
